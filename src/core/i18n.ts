type BaseTranslationKey = keyof typeof ES;
export type TranslationKey = BaseTranslationKey | RuntimeTranslationKey;
type TranslationTable = Record<TranslationKey, string>;

export const TRANSLATIONS: Record<Locale, TranslationTable> = {
	es: { ...ES, ...RUNTIME_CATALOG.es },
	en: { ...EN, ...RUNTIME_CATALOG.en },
};
export type TranslationParams = Record<string, string | number>;

export interface Translator {
	readonly locale: Locale;
	t(key: TranslationKey, params?: TranslationParams): string;
}

/** Typed catalogue lookup. Params are plain text only; callers must still escape their output surface. */
export function createTranslator(locale: Locale): Translator {
	return { locale, t: (key, params = {}) => interpolate(TRANSLATIONS[locale][key], params) };
}

export function isLocale(value: unknown): value is Locale { return value === 'es' || value === 'en'; }

function interpolate(template: string, params: TranslationParams): string {
	return template.replace(/\{\{([a-zA-Z0-9_]+)\}\}/gu, (_match, name: string) => String(params[name] ?? `{{${name}}}`));
}
import { RUNTIME_CATALOG, type RuntimeTranslationKey } from './i18n-runtime-catalog';
