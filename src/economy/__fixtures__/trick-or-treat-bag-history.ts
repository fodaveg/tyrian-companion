/**
 * The records in the endpoint's own shape.
 *
 * Recent records carry `buy_price_avg`; this is that half of the schema. The
 * parser's fallback for the older half, which has only `*_price_max` and
 * `*_price_min`, is covered by its own test rather than by mangling real rows.
 */
export function trickOrTreatBagHistoryRecords(): Record<string, unknown>[] {
	return ROWS.map(([date, buy, sell]) => ({
		date,
		buy_price_avg: buy,
		buy_price_max: buy,
		buy_price_min: buy,
		sell_price_avg: sell,
		sell_price_max: sell,
		sell_price_min: sell,
	}));
}

/** Distinct days present in the published series, for tests that only need membership. */
export function trickOrTreatBagHistoryDays(): string[] {
	return [...new Set(ROWS.map(([date]) => date))].sort();
}
